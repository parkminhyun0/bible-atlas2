def main():
    feats = []
    for ko, en, lon, lat, cert, period, desc, refs, src in SITES:
        props = {'ko': ko, 'en': en, 'cert': cert, 'period': period, 'desc': desc, 'src': src}
        if refs:
            props['refs'] = refs
        feats.append({'type': 'Feature', 'properties': props,
                      'geometry': {'type': 'Point', 'coordinates': [round(lon, 5), round(lat, 5)]}})

    fc = {'type': 'FeatureCollection',
          'attribution': '좌표: 이 저장소의 지명 자료 · OpenStreetMap (ODbL) · Wikidata (CC0)',
          'note': '1세기(제2성전기) 회당. 확실도 세 단계 — 발굴·논쟁·문헌.',
          'features': feats}
    OUT.write_text(json.dumps(fc, ensure_ascii=False, indent=1), encoding='utf-8')

    n = {}
    for f in feats:
        n[f['properties']['cert']] = n.get(f['properties']['cert'], 0) + 1
    print('%d곳 · %s' % (len(feats), n))
    print('%s  %.1f KB' % (OUT, OUT.stat().st_size / 1024))


if __name__ == '__main__':
    main()
